def add_bordes_to_board(board):
    border_value = 99
    num_cols = len(board[0]) + 2
    horizontal_border = (border_value,) * num_cols
    bordered_rows = [(border_value,) + row + (border_value,) for row in board]
    full_board = [horizontal_border] + bordered_rows + [horizontal_border]
    return tuple(full_board)



